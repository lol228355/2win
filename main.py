# Создаем клиента. Сессия сохранится в файл, привязанный к PHONE_NUMBER.
client = TelegramClient(PHONE_NUMBER, API_ID, API_HASH)


async def main():
    # Поскольку мы используем 'with client:', вход и подключение уже произошли.
    # Больше не нужно вызывать client.start()
    print("Успешное подключение! Сессия загружена. Переход к отправке.")

    # Проверяем, удалось ли найти получателя
    try:
        receiver = await client.get_input_entity(TARGET_USERNAME)
    except Exception as e:
        print(f"Ошибка: Не удалось найти пользователя {TARGET_USERNAME}. Проверьте его имя пользователя.")
        return

    print(f"Начинаю отправку {len(animals)} сообщений в чат {TARGET_USERNAME}...")

    # Отправка сообщений
    for animal in animals:
        try:
            await client.send_message(receiver, animal)
            print(f"Отправлено: {animal}")
            time.sleep(MESSAGE_DELAY)  # Задержка
        except Exception as e:
            print(f"Ошибка при отправке {animal}: {e.__class__.__name__}. Ожидание 10 секунд...")
            time.sleep(10)

    print("Готово! Все сообщения отправлены.")
    # client.disconnect() будет вызван автоматически блоком 'with client:'


# Запуск асинхронной функции
with client:
    # Здесь происходит подключение и загрузка сессии.
    client.loop.run_until_complete(main())
